private val countPattern = Regex("^(\\d+) (songs|albums|artists|minutes|seconds)$")

private fun dynamicPortuguese(text: String): String {
    countPattern.matchEntire(text)?.let { match ->
        val quantity = match.groupValues[1]
        val unit = when (match.groupValues[2]) {
            "songs" -> if (quantity == "1") "música" else "músicas"
            "albums" -> if (quantity == "1") "álbum" else "álbuns"
            "artists" -> if (quantity == "1") "artista" else "artistas"
            "minutes" -> if (quantity == "1") "minuto" else "minutos"
            else -> if (quantity == "1") "segundo" else "segundos"
        }
        return "$quantity $unit"
    }
    return text
}
